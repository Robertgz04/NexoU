/**
 * SHA-256 en TypeScript puro (sin dependencias nativas).
 * Se usa para guardar contraseñas de forma irreversible (F01/F02),
 * con sal derivada del correo del usuario.
 *
 * Verificado en `__tests__/sha256.test.ts` contra Node's crypto.
 */

